    static class TreeNode {
        int val;
        TreeNode left;
        TreeNode right;

        TreeNode(int val) {
            this.val = val;
            this.left = null;
            this.right = null;
        }
    }

    /**
     * Serializes a binary tree into standard space-separated level-order tokens.
     * Uses an index-pointer queue to handle null entries safely.
     */
    static String serialize(TreeNode root) {
        if (root == null) {
            return "null";
        }

        ArrayList<String> tokens = new ArrayList<>();
        ArrayList<TreeNode> queue = new ArrayList<>();
        queue.add(root);
        int head = 0;

        while (head < queue.size()) {
            TreeNode current = queue.get(head++);
            if (current != null) {
                tokens.add(Integer.toString(current.val));
                queue.add(current.left);
                queue.add(current.right);
            } else {
                tokens.add("null");
            }
        }

        // Strip trailing "null" tokens
        int last = tokens.size() - 1;
        while (last >= 0 && tokens.get(last).equals("null")) {
            last--;
        }

        if (last < 0) {
            return "null";
        }

        StringBuilder sb = new StringBuilder();
        for (int i = 0; i <= last; i++) {
            if (i > 0) {
                sb.append(' ');
            }
            sb.append(tokens.get(i));
        }

        return sb.toString();
    }

    /**
     * Optimal internal solver to determine if a binary tree satisfies the children sum property.
     * Uses stack-safe iterative BFS traversal.
     */
    static boolean solve(TreeNode root) {
        if (root == null) {
            return true;
        }

        ArrayDeque<TreeNode> queue = new ArrayDeque<>();
        queue.add(root);

        while (!queue.isEmpty()) {
            TreeNode curr = queue.poll();

            // Leaf nodes trivially satisfy the property
            if (curr.left == null && curr.right == null) {
                continue;
            }

            int childSum = (curr.left != null ? curr.left.val : 0) +
                           (curr.right != null ? curr.right.val : 0);

            if (curr.val != childSum) {
                return false;
            }

            if (curr.left != null) {
                queue.add(curr.left);
            }
            if (curr.right != null) {
                queue.add(curr.right);
            }
        }

        return true;
    }

    /**
     * Writes content to a file.
     */
    static void writeFile(File file, String content) throws IOException {
        File parent = file.getParentFile();
        if (parent != null && !parent.exists()) {
            parent.mkdirs();
        }
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(file))) {
            writer.write(content);
            writer.newLine();
        }
    }

    /**
     * Collects all nodes in BFS order.
     */
    static ArrayList<TreeNode> getBfsOrder(TreeNode root) {
        ArrayList<TreeNode> list = new ArrayList<>();
        if (root == null) return list;
        ArrayDeque<TreeNode> queue = new ArrayDeque<>();
        queue.add(root);
        while (!queue.isEmpty()) {
            TreeNode curr = queue.poll();
            list.add(curr);
            if (curr.left != null) queue.add(curr.left);
            if (curr.right != null) queue.add(curr.right);
        }
        return list;
    }

    /**
     * Sets values bottom-up so that the tree strictly satisfies the children sum property.
     * Leaves are given values generated by leafSupplier.
     */
    interface LeafValueSupplier {
        int get();
    }

    static void makeValidBottomUp(TreeNode root, LeafValueSupplier leafSupplier) {
        if (root == null) return;
        ArrayList<TreeNode> bfs = getBfsOrder(root);
        // Process in reverse BFS order (postorder / bottom-up)
        for (int i = bfs.size() - 1; i >= 0; i--) {
            TreeNode node = bfs.get(i);
            if (node.left == null && node.right == null) {
                node.val = leafSupplier.get();
            } else {
                int leftVal = (node.left != null ? node.left.val : 0);
                int rightVal = (node.right != null ? node.right.val : 0);
                long sum = (long) leftVal + (long) rightVal;
                // Clamp within [-100000, 100000] if necessary
                if (sum > 100000) sum = 100000;
                if (sum < -100000) sum = -100000;
                node.val = (int) sum;
            }
        }
    }

    /**
     * Builds a random binary tree structure with n nodes.
     */
    static TreeNode buildRandomStructure(int n, Random rng) {
        if (n <= 0) return null;
        TreeNode root = new TreeNode(0);
        ArrayList<TreeNode> candidates = new ArrayList<>();
        candidates.add(root);
        int created = 1;

        while (created < n && !candidates.isEmpty()) {
            int idx = rng.nextInt(candidates.size());
            TreeNode parent = candidates.get(idx);

            boolean attachLeft = parent.left == null && (parent.right != null || rng.nextBoolean());
            if (attachLeft) {
                parent.left = new TreeNode(0);
                candidates.add(parent.left);
                created++;
            } else if (parent.right == null) {
                parent.right = new TreeNode(0);
                candidates.add(parent.right);
                created++;
            }

            if (parent.left != null && parent.right != null) {
                int lastIdx = candidates.size() - 1;
                candidates.set(idx, candidates.get(lastIdx));
                candidates.remove(lastIdx);
            }
        }
        return root;
    }

    /**
     * Builds a complete binary tree structure with n nodes.
     */
    static TreeNode buildCompleteStructure(int n) {
        if (n <= 0) return null;
        TreeNode[] nodes = new TreeNode[n];
        for (int i = 0; i < n; i++) {
            nodes[i] = new TreeNode(0);
        }
        for (int i = 0; i < n; i++) {
            int leftIdx = 2 * i + 1;
            int rightIdx = 2 * i + 2;
            if (leftIdx < n) nodes[i].left = nodes[leftIdx];
            if (rightIdx < n) nodes[i].right = nodes[rightIdx];
        }
        return nodes[0];
    }

